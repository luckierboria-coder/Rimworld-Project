function Replace-OrThrow {
  param([string]$Text,[string]$Old,[string]$New,[string]$Label)
  if(-not $Text.Contains($Old)){ throw "T32-B.1 anchor missing: $Label" }
  return $Text.Replace($Old,$New)
}

# T32-B.1 Adaptive Forbidden Fingerprint
# Applied on top of verified T32-B.
#
# Shared primitive policy only:
# - each ValidatorTrustState (original validator method + scanner instance) learns its own
#   first-repeat/store ratio; no WorkGiver/mod name is consulted.
# - mode starts Lazy.
# - Lazy -> Eager only after the existing T21 validator trust is warm AND >=128 stores with
#   >=12.5% first-repeat rate.
# - Eager -> Lazy after >=256 stores with <6.25% first-repeat rate.
# - hysteresis prevents mode flapping; evidence is bounded by periodic halving.
# - Lazy stores keep T32-B semantics: no store-time IsForbidden; first repeat stays live.
# - Eager stores capture Forbidden immediately, so the first repeat can use the original
#   T21 warmup/sampled-parity/authoritative replay path.
# - any eager capture failure falls back to Lazy for that entry.
# - false-only authority, parity, mismatch quarantine, package lifetime and zero-wait remain unchanged.

